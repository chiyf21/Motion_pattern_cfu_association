#!/usr/bin/env python3
"""
Global all-slice motion-pattern x CFU lag co-occurrence.

Statistical procedure
---------------------
For every motion-pattern / CFU pair:

1. Evaluate lagged co-occurrence for lag = -8 ... +8.
2. For each lag, calculate a binomial enrichment p-value.
3. Convert the lag-wise p-value to an enrichment score:
       score = -log10(p)
4. Define the pair statistic as the maximum score across all lags:
       S_pair = max_lag score(lag)

The 17-lag search is therefore part of the pair statistic and is NOT
Bonferroni-corrected separately.

Global multiple-testing correction
----------------------------------
A shift-null is constructed by applying the SAME circular temporal shift
to all CFU onset trains simultaneously. This preserves:

- the number of onsets in every CFU,
- temporal structure within every CFU,
- relative timing among different CFUs,
- all motion-pattern timing,

while destroying the absolute Ca-vs-motion temporal alignment.

For every null shift, the COMPLETE analysis is repeated, including the
search over all 17 lags for all pattern-CFU pairs.

For score threshold s:

    R_obs(s) = number of observed pairs with score >= s

    V_null(s) = expected number of null pairs with score >= s

and

    empirical_FDR(s) = V_null(s) / R_obs(s)

Pair-level empirical q-values are obtained from the monotone FDR envelope.

IMPORTANT
---------
CFU timing uses cfuInfo1{i,4}, i.e. the AQuA2 CFU rising-time/onset
binary timeline generated by getRisingTime(), NOT res.fts1.loc.t0.
"""

