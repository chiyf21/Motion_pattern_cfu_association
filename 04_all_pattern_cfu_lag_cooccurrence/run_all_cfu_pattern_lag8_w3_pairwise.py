def _detect_cfu_cell_layout(cells):
    """
    MATLAB cell arrays are dimension-reversed when viewed through h5py.

    Typical MATLAB:
        nCFU x 9

    appears as:
        9 x nCFU

    in HDF5/h5py.
    """

    if cells.ndim != 2:
        raise RuntimeError(
            f"Unexpected cfuInfo1 shape: {cells.shape}"
        )

    # Standard AQuA2 cfuInfo1 has 9 fields.
    # Some newer versions may have 10.
    if cells.shape[0] in (9, 10):
        return "field_first", cells.shape[1]

    if cells.shape[1] in (9, 10):
        return "cfu_first", cells.shape[0]

    raise RuntimeError(
        "Cannot determine cfuInfo1 orientation. "
        f"Shape = {cells.shape}"
    )


def _get_cfu_field_ref(cells, layout, cid0, field0):
    """Get the HDF5 reference for one CFU field."""

    if layout == "field_first":
        return cells[field0, cid0]

    return cells[cid0, field0]


def cfu_event_onsets(z):
    """
    Read AQuA2 CFU onset timelines.

    Uses:
        cfuInfo1{i,4}

    which corresponds to the binary CFU occurrence/onset timeline
    calculated by cfu.getRisingTime().

    Returns
    -------
    list of tuples:
        (
            cfu_id_1based,
            n_member_events,
            onset_frames_0based
        )
    """

    cfu_file = (
        CFU_BASE
        / f"slice_Z{z:02d}_ds7_native_CFU_ot030_min5_group5.mat"
    )

    out = []

    with h5py.File(cfu_file, "r") as cf:

        cells = cf["cfuInfo1"]

        layout, n_cfus = _detect_cfu_cell_layout(cells)

        for cid0 in range(n_cfus):

            # ------------------------------------------------
            # Column 2 in MATLAB:
            # cfuInfo1{i,2} = member event IDs
            # ------------------------------------------------

            member_ref = _get_cfu_field_ref(
                cells,
                layout,
                cid0,
                field0=1,
            )

            member_ids = np.asarray(
                cf[member_ref]
            ).reshape(-1)

            n_member_events = len(member_ids)


            # ------------------------------------------------
            # Column 4 in MATLAB:
            # cfuInfo1{i,4} = onset/occurrence binary timeline
            # ------------------------------------------------

            onset_ref = _get_cfu_field_ref(
                cells,
                layout,
                cid0,
                field0=3,
            )

            onset_timeline = np.asarray(
                cf[onset_ref]
            ).reshape(-1)

            if onset_timeline.size != T:
                raise RuntimeError(
                    f"CFU onset timeline length mismatch: "
                    f"slice={z}, cfu={cid0 + 1}, "
                    f"found={onset_timeline.size}, expected={T}"
                )

            onsets = np.flatnonzero(onset_timeline > 0)

            onsets = np.asarray(
                onsets,
                dtype=np.int32,
            )

            out.append(
                (
                    cid0 + 1,
                    n_member_events,
                    onsets,
                )
            )

    return out


