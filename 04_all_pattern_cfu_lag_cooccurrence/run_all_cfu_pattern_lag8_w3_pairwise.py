# Main
# ============================================================

def main():

    RESULTS.mkdir(
        parents=True,
        exist_ok=True,
    )


    # ========================================================
    # Load motion patterns and CFUs
    # ========================================================

    patterns = []
    cfus = []

    for z in range(1, 13):

        patterns += [
            (
                z,
                pid,
                nm,
                peaks,
            )
            for pid, nm, peaks
            in motion_event_peaks(z)
        ]

        cfus += [
            (
                z,
                cid,
                n_member_events,
                onsets,
            )
            for cid, n_member_events, onsets
            in cfu_event_onsets(z)
        ]


    n_patterns = len(patterns)
    n_cfus = len(cfus)
    n_pairs = n_patterns * n_cfus
    n_lag_tests = n_pairs * len(LAGS)


    print(
        f"patterns={n_patterns}",
        f"cfus={n_cfus}",
        f"pairs={n_pairs}",
        f"lag_evaluations={n_lag_tests}",
        flush=True,
    )


    # ========================================================
    # Build CFU onset matrix
    # ========================================================

    onset_matrix = build_onset_matrix(
        cfus
    )

    observed_window_hits = build_window_hit_matrix(
        onset_matrix
    )


    # ========================================================
    # CFU baseline onset rates
    # ========================================================

    cfu_n_onsets = np.asarray(
        [
            len(onsets)
            for _, _, _, onsets
            in cfus
        ],
        dtype=float,
    )

    burst_rate = (
        cfu_n_onsets
        /
        T
    )

    p_window = (
        1.0
        -
        (1.0 - burst_rate) ** WINDOW_W
    )

    p_window = np.clip(
        p_window,
        0.0,
        1.0,
    )


    # ========================================================
    # Precompute motion lag windows
    # ========================================================

    (
        pattern_lag_starts,
        unique_n_trials,
    ) = precompute_pattern_lag_starts(
        patterns
    )


    # ========================================================
    # Binomial lookup tables
    # ========================================================

    (
        p_tables,
        score_tables,
    ) = build_binomial_lookup(
        unique_n_trials,
        p_window,
    )


    # ========================================================
    # Observed best-lag statistics
    # ========================================================

    print(
        "Calculating observed best-lag pair statistics...",
        flush=True,
    )

    (
        best_score,
        best_p,
        best_lag,
        best_k,
        best_n_trials,
    ) = compute_best_pair_scores(
        observed_window_hits,
        pattern_lag_starts,
        p_tables,
        score_tables,
        return_details=True,
    )


    # ========================================================
    # Global empirical FDR
    # ========================================================

    (
        q_matrix,
        threshold_rows,
        null_shifts,
    ) = empirical_global_fdr(
        best_score,
        onset_matrix,
        pattern_lag_starts,
        p_tables,
        score_tables,
    )


    # ========================================================
    # Pair-level output
    # ========================================================

    pair_rows = []
    sig_rows = []

    for pi, (
        ms,
        pid,
        nm,
        peaks,
    ) in enumerate(patterns):

        for ci, (
            cs,
            cid,
            n_member_events,
            onsets,
        ) in enumerate(cfus):

            q = float(
                q_matrix[pi, ci]
            )

            row = {
                "motion_slice_0based": ms,
                "pattern_id": pid,
                "cfu_slice_0based": cs,
                "cfu_id": cid,
                "pattern_n_members": nm,
                "n_motion_events": len(peaks),
                "cfu_n_member_events": n_member_events,
                "cfu_n_onsets": len(onsets),
                "best_lag": int(
                    best_lag[pi, ci]
                ),
                "window_frames": WINDOW_W,
                "n_valid_motion_events_at_best_lag": int(
                    best_n_trials[pi, ci]
                ),
                "k_hit_motion_events_at_best_lag": int(
                    best_k[pi, ci]
                ),
                "p_window": float(
                    p_window[ci]
                ),
                "best_lag_binomial_p": float(
                    best_p[pi, ci]
                ),
                "pair_score": float(
                    best_score[pi, ci]
                ),
                "q_empirical_global": q,
                "significant": int(
                    q <= FDR_ALPHA
                ),
            }

            pair_rows.append(row)

            if q <= FDR_ALPHA:
                sig_rows.append(row)


    save_csv(
        RESULTS
        / "all_pair_best_lag_statistics.csv",
        pair_rows,
    )

    save_csv(
        RESULTS
        / "empirical_FDR_significant_pairs.csv",
        sig_rows,
    )

    save_csv(
        RESULTS
        / "empirical_fdr_thresholds.csv",
        threshold_rows,
    )


    # ========================================================
    # Save null shifts
    # ========================================================

    shift_rows = [
        {
            "shift_frames": int(s),
            "shift_seconds": float(
                s * FRAME_SECONDS
            ),
            "circular_distance_frames": int(
                min(s, T - s)
            ),
        }
        for s in null_shifts
    ]

    save_csv(
        RESULTS / "null_shifts.csv",
        shift_rows,
    )


    # ========================================================
    # Optional all-lag output
    # ========================================================

    if SAVE_ALL_LAG_ROWS:

        print(
            "Writing all lag-wise statistics...",
            flush=True,
        )

        write_all_lag_statistics(
            RESULTS
            / "all_pair_lag_statistics.csv",
            patterns,
            cfus,
            observed_window_hits,
            pattern_lag_starts,
            p_window,
            p_tables,
            score_tables,
            best_lag,
            best_score,
            q_matrix,
        )


    # ========================================================
    # Summary
    # ========================================================

    n_sig = int(
        np.sum(
            q_matrix <= FDR_ALPHA
        )
    )

    summary = [
        {
            "n_patterns": n_patterns,
            "n_cfus": n_cfus,
            "n_unique_pairs": n_pairs,
            "n_lag_values": len(LAGS),
            "n_total_lag_evaluations": n_lag_tests,
            "n_null_shifts": len(null_shifts),
            "null_guard_frames": NULL_GUARD_FRAMES,
            "window_frames": WINDOW_W,
            "lag_min": LAG_MIN,
            "lag_max": LAG_MAX,
            "fdr_alpha": FDR_ALPHA,
            "n_significant_pairs": n_sig,
        }
    ]

    save_csv(
        RESULTS / "summary_global.csv",
        summary,
    )


    # ========================================================
    # Save configuration
    # ========================================================

    config_text = f"""
Global all-slice motion-pattern x CFU onset co-occurrence

CFU timing:
    AQuA2 cfuInfo1{{i,4}} rising-time/onset timeline

Patterns retained:
    pattern members >= {MIN_PATTERN_MEMBERS}
    motion events >= {MIN_MOTION_EVENTS}

Motion event detection:
    RMS activity
    find_peaks prominence = {MOTION_PROMINENCE_FACTOR} * SD
    minimum peak distance = {MOTION_MIN_DISTANCE} frames

Co-occurrence:
    window = {WINDOW_W} frames
    lag = {LAG_MIN} ... {LAG_MAX}

Pair statistic:
    lag-wise binomial enrichment p-value
    score(lag) = -log10(p)
    pair_score = max_lag score(lag)

Lag multiple testing:
    No Bonferroni correction.
    The complete lag search is repeated inside every null realization.

Null:
    Same circular temporal shift applied to ALL CFUs.
    Near-zero shifts excluded:
        circular distance <= {NULL_GUARD_FRAMES} frames

Number of null shifts:
    {len(null_shifts)}

Global correction:
    empirical_FDR(score threshold)
        =
    expected_null_discoveries
        /
    observed_discoveries

Significance:
    empirical global q <= {FDR_ALPHA}
"""

    (
        OUT
        / "run_config.txt"
    ).write_text(
        config_text.strip() + "\n"
    )


    print(
        summary[0],
        flush=True,
    )


if __name__ == "__main__":
    main()
