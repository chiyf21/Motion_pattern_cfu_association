# Optional: save all lag-wise statistics
# ============================================================

def write_all_lag_statistics(
    path,
    patterns,
    cfus,
    window_hits,
    pattern_lag_starts,
    p_window,
    p_tables,
    score_tables,
    best_lag,
    best_score,
    q_matrix,
):
    """
    Recompute observed lag-wise statistics and stream them to disk.

    This avoids holding ~6.5 million Python dictionaries in memory.
    """

    path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    fields = [
        "motion_slice_0based",
        "pattern_id",
        "cfu_slice_0based",
        "cfu_id",
        "pattern_n_members",
        "n_motion_events",
        "cfu_n_member_events",
        "cfu_n_onsets",
        "lag",
        "window_frames",
        "n_valid_motion_events",
        "k_hit_motion_events",
        "p_window",
        "p_value_binomial",
        "lag_score",
        "pair_best_lag",
        "pair_best_score",
        "q_empirical_global",
        "significant_pair",
        "significant_best_lag",
    ]

    cfu_idx = np.arange(
        len(cfus)
    )

    with path.open(
        "w",
        newline="",
    ) as f:

        writer = csv.writer(f)

        writer.writerow(fields)

        for pi, (
            ms,
            pid,
            nm,
            peaks,
        ) in enumerate(patterns):

            for li, lag in enumerate(LAGS):

                starts = pattern_lag_starts[pi][li]

                n_trials = len(starts)

                if n_trials == 0:
                    continue

                k = np.sum(
                    window_hits[:, starts],
                    axis=1,
                ).astype(np.int16)

                pvals = p_tables[n_trials][
                    cfu_idx,
                    k,
                ]

                scores = score_tables[n_trials][
                    cfu_idx,
                    k,
                ]

                rows = []

                for ci, (
                    cs,
                    cid,
                    n_member_events,
                    onsets,
                ) in enumerate(cfus):

                    pair_sig = (
                        q_matrix[pi, ci]
                        <= FDR_ALPHA
                    )

                    is_best = (
                        int(lag)
                        ==
                        int(best_lag[pi, ci])
                    )

                    rows.append(
                        [
                            ms,
                            pid,
                            cs,
                            cid,
                            nm,
                            len(peaks),
                            n_member_events,
                            len(onsets),
                            int(lag),
                            WINDOW_W,
                            n_trials,
                            int(k[ci]),
                            float(p_window[ci]),
                            float(pvals[ci]),
                            float(scores[ci]),
                            int(best_lag[pi, ci]),
                            float(best_score[pi, ci]),
                            float(q_matrix[pi, ci]),
                            int(pair_sig),
                            int(
                                pair_sig
                                and is_best
                            ),
                        ]
                    )

                writer.writerows(rows)


