# Motion-pattern activity peaks
# ============================================================

def component_frames(c):
    """Extract frame indices and activity values from one component."""

    h = np.asarray(
        getattr(c, "activation", None),
        dtype=float,
    ).reshape(-1)

    tr = getattr(c, "time_range", None)

    if tr is None or not len(h):
        return (
            np.empty(0, dtype=int),
            np.empty(0, dtype=float),
        )

    a, b = int(tr[0]), int(tr[1])

    if b - a == len(h):
        frames = np.arange(a, b)

    elif b - a + 1 == len(h):
        frames = np.arange(a, b + 1)

    else:
        frames = np.arange(a, a + len(h))

    ok = (frames >= 0) & (frames < T)

    return frames[ok], h[ok]


def motion_event_peaks(z):
    """
    Extract motion occurrence peaks for all retained patterns
    from one slice.
    """

    path = (
        PAT_BASE
        / f"Slice{z:02d}_velocity_decomp"
        / "06_patterns"
        / "objects.pkl"
    )

    with path.open("rb") as f:
        patterns = pickle.load(f)["patterns"]

    out = []

    for p in patterns:

        n_members = int(p.n_members)

        if n_members < MIN_PATTERN_MEMBERS:
            continue

        comps = (
            getattr(p, "components", None)
            or getattr(p, "regions", [])
        )

        sq = np.zeros(T, dtype=float)
        count = np.zeros(T, dtype=np.int16)

        for c in comps:

            frames, h = component_frames(c)

            if len(frames):
                sq[frames] += h * h
                count[frames] += 1

        x = np.zeros(T, dtype=float)

        ok = count > 0

        x[ok] = np.sqrt(
            sq[ok] / count[ok]
        )

        x = np.nan_to_num(
            x,
            nan=np.nanmedian(x),
        )

        prom = max(
            MOTION_PROMINENCE_FACTOR * np.std(x),
            1e-8,
        )

        peaks, _ = find_peaks(
            x,
            prominence=prom,
            distance=MOTION_MIN_DISTANCE,
        )

        if len(peaks) >= MIN_MOTION_EVENTS:

            out.append(
                (
                    int(p.pattern_id),
                    n_members,
                    np.asarray(peaks, dtype=np.int32),
                )
            )

    return out


# ============================================================
# Build CFU onset matrix
# ============================================================

def build_onset_matrix(cfus):
    """
    Binary matrix:

        shape = (n_CFU, T)

    onset_matrix[c,t] = True
    if CFU c has an onset at frame t.
    """

    mat = np.zeros(
        (len(cfus), T),
        dtype=bool,
    )

    for ci, (_, _, _, onsets) in enumerate(cfus):

        if len(onsets):
            mat[ci, onsets] = True

    return mat


# ============================================================
# Window-hit matrix
# ============================================================

def build_window_hit_matrix(onset_matrix):
    """
    For every CFU and every possible window start s:

        hit[c,s] = 1

    if there is >=1 onset in:

        [s, s + WINDOW_W)

    Shape:
        (n_CFU, T - WINDOW_W + 1)
    """

    x = onset_matrix.astype(
        np.int32,
        copy=False,
    )

    prefix = np.concatenate(
        [
            np.zeros(
                (x.shape[0], 1),
                dtype=np.int32,
            ),
            np.cumsum(
                x,
                axis=1,
                dtype=np.int32,
            ),
        ],
        axis=1,
    )

    counts = (
        prefix[:, WINDOW_W:]
        -
        prefix[:, :-WINDOW_W]
    )

    return counts > 0


# ============================================================
# Precompute motion windows for every pattern / lag
# ============================================================

def precompute_pattern_lag_starts(patterns):
    """
    For every pattern and every lag, store valid window starts.

    Edge-invalid motion events are removed independently at each lag.
    """

    all_starts = []

    unique_n_trials = set()

    for _, _, _, peaks in patterns:

        per_pattern = []

        for lag in LAGS:

            starts = peaks + lag

            valid = (
                (starts >= 0)
                &
                (starts + WINDOW_W <= T)
            )

            starts = np.asarray(
                starts[valid],
                dtype=np.int32,
            )

            per_pattern.append(starts)

            if len(starts):
                unique_n_trials.add(
                    int(len(starts))
                )

        all_starts.append(per_pattern)

    return all_starts, sorted(unique_n_trials)


# ============================================================
# Precompute binomial score lookup tables
# ============================================================

def build_binomial_lookup(unique_n_trials, p_window):
    """
    Since n_trials and CFU baseline rate do not change across null shifts,
    precompute:

        p(K >= k | n, p_window)

    for every needed:
        n_trials
        CFU
        k
    """

    n_cfus = len(p_window)

    cfu_idx = np.arange(n_cfus)

    p_tables = {}
    score_tables = {}

    for n in unique_n_trials:

        k_values = np.arange(
            n + 1,
            dtype=int,
        )

        # Shape:
        #   (n_CFU, n+1)
        p_table = binom.sf(
            k_values[None, :] - 1,
            n,
            p_window[:, None],
        )

        p_table = np.clip(
            p_table,
            P_FLOOR,
            1.0,
        )

        score_table = -np.log10(
            p_table
        )

        p_tables[n] = p_table
        score_tables[n] = score_table

    return p_tables, score_tables


# ============================================================
# Calculate pair-wise best-lag statistic
# ============================================================

def compute_best_pair_scores(
    window_hits,
    pattern_lag_starts,
    p_tables,
    score_tables,
    return_details=False,
):
    """
    Calculate:

        S_pair = max_lag -log10(p_binomial)

    for every motion-pattern x CFU pair.
    """

    n_patterns = len(pattern_lag_starts)
    n_cfus = window_hits.shape[0]

    cfu_idx = np.arange(n_cfus)

    best_score = np.full(
        (n_patterns, n_cfus),
        -np.inf,
        dtype=np.float64,
    )

    if return_details:

        best_p = np.ones(
            (n_patterns, n_cfus),
            dtype=np.float64,
        )

        best_lag = np.full(
            (n_patterns, n_cfus),
            32767,
            dtype=np.int16,
        )

        best_k = np.zeros(
            (n_patterns, n_cfus),
            dtype=np.int16,
        )

        best_n_trials = np.zeros(
            (n_patterns, n_cfus),
            dtype=np.int16,
        )

    for pi, per_pattern in enumerate(pattern_lag_starts):

        for li, lag in enumerate(LAGS):

            starts = per_pattern[li]

            n_trials = len(starts)

            if n_trials == 0:
                continue

            # Number of motion occurrences that hit >=1 CFU onset
            #
            # window_hits[:, starts]:
            #     shape = (n_CFU, n_motion_events)
            #
            k = np.sum(
                window_hits[:, starts],
                axis=1,
            ).astype(np.int16)

            scores = score_tables[n_trials][
                cfu_idx,
                k,
            ]

            if not return_details:

                best_score[pi] = np.maximum(
                    best_score[pi],
                    scores,
                )

                continue


            pvals = p_tables[n_trials][
                cfu_idx,
                k,
            ]


            # Primary criterion:
            # larger score = stronger association
            better = (
                scores
                >
                best_score[pi] + 1e-12
            )


            # Tie breaking:
            #
            # If exactly equal evidence appears at several lags,
            # prefer the lag closer to zero.
            equal = np.isclose(
                scores,
                best_score[pi],
                rtol=0,
                atol=1e-12,
            )

            closer_to_zero = (
                np.abs(lag)
                <
                np.abs(best_lag[pi])
            )

            update = (
                better
                |
                (equal & closer_to_zero)
            )


            best_score[pi, update] = scores[update]

            best_p[pi, update] = pvals[update]

            best_lag[pi, update] = lag

            best_k[pi, update] = k[update]

            best_n_trials[pi, update] = n_trials


    if not return_details:

        return best_score


    return (
        best_score,
        best_p,
        best_lag,
        best_k,
        best_n_trials,
    )


# ============================================================
# Null circular shifts
# ============================================================

def choose_null_shifts():
    """
    Select global circular shifts.

    Small shifts are excluded because they can be compensated by the
    +/-8-frame lag search.
    """

    valid = []

    for shift in range(1, T):

        circular_distance = min(
            shift,
            T - shift,
        )

        if circular_distance <= NULL_GUARD_FRAMES:
            continue

        valid.append(shift)

    valid = np.asarray(
        valid,
        dtype=np.int32,
    )

    if (
        N_NULL_SHIFTS is None
        or N_NULL_SHIFTS >= len(valid)
    ):

        return valid

    rng = np.random.default_rng(
        RANDOM_SEED
    )

    shifts = rng.choice(
        valid,
        size=N_NULL_SHIFTS,
        replace=False,
    )

    return np.sort(shifts)


# ============================================================
# Empirical global FDR
# ============================================================

def empirical_global_fdr(
    observed_scores,
    onset_matrix,
    pattern_lag_starts,
    p_tables,
    score_tables,
):
    """
    Estimate global empirical FDR using whole-Ca-system circular shifts.
    """

    observed_flat = observed_scores.reshape(-1)

    n_pairs = len(observed_flat)


    # --------------------------------------------------------
    # Unique observed score thresholds
    # --------------------------------------------------------

    thresholds_asc, inverse = np.unique(
        observed_flat,
        return_inverse=True,
    )

    thresholds_desc = thresholds_asc[::-1]


    # --------------------------------------------------------
    # Number of observed discoveries at each threshold
    # --------------------------------------------------------

    observed_sorted = np.sort(
        observed_flat
    )

    n_observed = (
        n_pairs
        -
        np.searchsorted(
            observed_sorted,
            thresholds_desc,
            side="left",
        )
    ).astype(np.float64)


    # --------------------------------------------------------
    # Null shifts
    # --------------------------------------------------------

    shifts = choose_null_shifts()

    null_exceed_sum = np.zeros(
        len(thresholds_desc),
        dtype=np.float64,
    )

    print(
        f"Running {len(shifts)} global circular-shift nulls...",
        flush=True,
    )

    for bi, shift in enumerate(shifts, start=1):

        # Same temporal shift for EVERY CFU.
        shifted_onsets = np.roll(
            onset_matrix,
            shift=int(shift),
            axis=1,
        )

        shifted_hits = build_window_hit_matrix(
            shifted_onsets
        )

        null_scores = compute_best_pair_scores(
            shifted_hits,
            pattern_lag_starts,
            p_tables,
            score_tables,
            return_details=False,
        )

        null_flat = np.sort(
            null_scores.reshape(-1)
        )

        n_null = (
            n_pairs
            -
            np.searchsorted(
                null_flat,
                thresholds_desc,
                side="left",
            )
        )

        null_exceed_sum += n_null


        if (
            bi == 1
            or bi % 10 == 0
            or bi == len(shifts)
        ):

            print(
                f"  null shift {bi}/{len(shifts)} "
                f"(shift={int(shift)} frames)",
                flush=True,
            )


    # --------------------------------------------------------
    # Expected number of false discoveries
    # --------------------------------------------------------
    #
    # Add-one smoothing avoids an exact zero estimate.
    #

    mean_null_discoveries = (
        1.0 + null_exceed_sum
    ) / (
        len(shifts) + 1.0
    )


    # --------------------------------------------------------
    # Raw empirical FDR
    # --------------------------------------------------------

    fdr_raw_desc = (
        mean_null_discoveries
        /
        np.maximum(
            n_observed,
            1.0,
        )
    )

    fdr_raw_desc = np.minimum(
        fdr_raw_desc,
        1.0,
    )


    # --------------------------------------------------------
    # Convert threshold FDR to monotone q-values
    # --------------------------------------------------------
    #
    # thresholds_desc:
    #
    # high score -> low score
    #
    # q(s) =
    #   minimum FDR among all thresholds that still include score s
    #

    q_desc = np.minimum.accumulate(
        fdr_raw_desc[::-1]
    )[::-1]


    # Convert back to ascending threshold ordering
    q_asc = q_desc[::-1]

    q_flat = q_asc[inverse]

    q_matrix = q_flat.reshape(
        observed_scores.shape
    )


    threshold_rows = []

    for i, threshold in enumerate(thresholds_desc):

        threshold_rows.append(
            {
                "score_threshold": float(threshold),
                "n_observed_pairs_ge_threshold": int(
                    n_observed[i]
                ),
                "mean_null_pairs_ge_threshold": float(
                    mean_null_discoveries[i]
                ),
                "empirical_fdr_raw": float(
                    fdr_raw_desc[i]
                ),
                "empirical_q": float(
                    q_desc[i]
                ),
            }
        )


    return (
        q_matrix,
        threshold_rows,
        shifts,
    )


